def main() -> None:
    rows = json.loads((DATA / "cards.json").read_text(encoding="utf-8"))
    filled = 0
    for r in rows:
        if r["카드ID"] in FIX:
            r["교정문장"] = FIX[r["카드ID"]]
            r["교정출처"] = "보강(2026-10-17, 카드 본문 근거)"
            filled += 1
        else:
            r.setdefault("교정출처", "원문 추출" if r["교정문장"] else "")
    (DATA / "cards_fixed.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")

    cols = ["카드ID", "회차", "형식", "원칙", "요지", "교정문장", "교정출처", "URL", "본문"]
    with (ROOT / "사례카드.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({**r, "URL": " | ".join(r["URL"])})

    B = [r for r in rows if r["형식"] == "B"]
    nofix = [r for r in B if not r["교정문장"]]
    print(f"보강 적용 {filled}장 · cards_fixed.json · 사례카드.csv 재생성")
    print(f"  B형 {len(B)}장 중 교정문장 보유 {len(B)-len(nofix)}장 / 없음 {len(nofix)}장")
    if nofix:
        print("  남은 대상:", ", ".join(r["카드ID"] for r in nofix))


if __name__ == "__main__":
    main()
